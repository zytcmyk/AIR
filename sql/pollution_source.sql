-- 污染源分析相关表

-- 1. 污染源类型表
DROP TABLE IF EXISTS `source_type`;
CREATE TABLE `source_type` (
  `id` int NOT NULL AUTO_INCREMENT COMMENT '主键',
  `type_name` varchar(50) NOT NULL COMMENT '类型名称',
  `type_code` varchar(20) NOT NULL COMMENT '类型编码',
  `color` varchar(20) DEFAULT NULL COMMENT '显示颜色',
  `description` varchar(200) DEFAULT NULL COMMENT '描述',
  `sort_order` int DEFAULT 0 COMMENT '排序',
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='污染源类型表';

-- 2. 污染源子类型表
DROP TABLE IF EXISTS `source_subtype`;
CREATE TABLE `source_subtype` (
  `id` int NOT NULL AUTO_INCREMENT COMMENT '主键',
  `parent_id` int NOT NULL COMMENT '父类型ID',
  `subtype_name` varchar(50) NOT NULL COMMENT '子类型名称',
  `description` varchar(200) DEFAULT NULL COMMENT '描述',
  PRIMARY KEY (`id`),
  KEY `idx_parent_id` (`parent_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='污染源子类型表';

-- 3. 城市污染源贡献数据表
DROP TABLE IF EXISTS `city_source_contribution`;
CREATE TABLE `city_source_contribution` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键',
  `city` varchar(50) NOT NULL COMMENT '城市',
  `source_type_id` int NOT NULL COMMENT '污染源类型ID',
  `contribution_rate` decimal(5,2) NOT NULL COMMENT '贡献率(%)',
  `record_date` date NOT NULL COMMENT '记录日期',
  `create_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`),
  KEY `idx_city_date` (`city`, `record_date`),
  KEY `idx_source_type` (`source_type_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='城市污染源贡献数据表';

-- 4. 污染源趋势数据表
DROP TABLE IF EXISTS `source_trend`;
CREATE TABLE `source_trend` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键',
  `city` varchar(50) NOT NULL COMMENT '城市',
  `source_type_id` int NOT NULL COMMENT '污染源类型ID',
  `period_type` varchar(20) NOT NULL COMMENT '周期类型:week/month/quarter',
  `period_value` varchar(20) NOT NULL COMMENT '周期值(如:2024-01)',
  `contribution_rate` decimal(5,2) NOT NULL COMMENT '贡献率(%)',
  `create_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_city_source_period` (`city`, `source_type_id`, `period_type`, `period_value`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='污染源趋势数据表';

-- 5. 城市污染源排名表
DROP TABLE IF EXISTS `city_source_ranking`;
CREATE TABLE `city_source_ranking` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键',
  `city` varchar(50) NOT NULL COMMENT '城市',
  `main_source_type` varchar(50) NOT NULL COMMENT '主要污染源类型',
  `main_contribution_rate` decimal(5,2) NOT NULL COMMENT '主要污染源贡献率(%)',
  `total_contribution` decimal(5,2) DEFAULT 0 COMMENT '总贡献率',
  `rank_order` int DEFAULT 0 COMMENT '排名',
  `record_date` date NOT NULL COMMENT '记录日期',
  `create_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`),
  KEY `idx_city` (`city`),
  KEY `idx_rank` (`rank_order`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='城市污染源排名表';

-- 6. 污染源相关性数据表
DROP TABLE IF EXISTS `source_correlation`;
CREATE TABLE `source_correlation` (
  `id` int NOT NULL AUTO_INCREMENT COMMENT '主键',
  `source_type_1` varchar(50) NOT NULL COMMENT '污染源类型1',
  `source_type_2` varchar(50) NOT NULL COMMENT '污染源类型2',
  `correlation_value` decimal(4,2) NOT NULL COMMENT '相关系数',
  `description` varchar(200) DEFAULT NULL COMMENT '相关性描述',
  `create_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='污染源相关性数据表';

